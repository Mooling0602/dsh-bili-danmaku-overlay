/**
 * Bundles both halves of the plugin.
 *
 * ── Why the Client half has to be bundled ──────────────────────────────────
 *
 * `window.__ModuleLoader__.load({ id, factory(require) })` hands the plugin a
 * `require` that resolves *host* packages only; it cannot resolve relative module
 * specifiers. The Client half must therefore be one self-contained file, which is
 * what esbuild produces here.
 *
 * ── Why the Host half is bundled too ───────────────────────────────────────
 *
 * The Host evaluates plain ESM and the Node build in use has no TypeScript
 * stripping, so `host.ts` cannot be imported directly. Bundling also keeps the
 * relative `.ts` specifiers out of the shipped file.
 *
 * Usage: node build.mjs
 */

import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const manifest = JSON.parse(await readFile(resolve(here, 'package.json'), 'utf8'))

const name = manifest.name
if (typeof name !== 'string' || name.length === 0) {
  throw new Error('package.json must declare a `name`')
}

/** Packages the Client loader provides; never bundled. */
const CLIENT_EXTERNAL = [
  'react',
  'react-dom',
  'react/jsx-runtime',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-slots',
]

/** Host packages resolved from the Host's own tree. */
const HOST_EXTERNAL = ['@deepseek-ai/schemastery', '@deepseek-ai/cordis']

/** IIFE global, derived from the package name so two bundles cannot collide. */
const globalName = '__dsh_' + name.replace(/^@/, '').replace(/[^a-zA-Z0-9]/g, '_')

const clientResult = await build({
  entryPoints: [resolve(here, 'src/client/index.tsx')],
  bundle: true,
  write: false,
  format: 'iife',
  globalName,
  platform: 'browser',
  target: 'es2022',
  legalComments: 'none',
  logLevel: 'warning',
  // Keep CJK literals readable in the shipped bundle instead of \uXXXX escapes.
  charset: 'utf8',
  jsx: 'automatic',
  external: CLIENT_EXTERNAL,
})

const clientBundle = clientResult.outputFiles?.[0]
if (!clientBundle) throw new Error('esbuild produced no client output')

const indented = clientBundle.text
  .trim()
  .split('\n')
  .map((line) => (line.length === 0 ? '' : `    ${line}`))
  .join('\n')

const wrapped = `/**
 * ${name} — Client half.
 *
 * Generated by build.mjs from src/client/*. Source of truth is the TypeScript;
 * do not edit this file by hand.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(name)},
  factory(require) {
    'use strict';
    const module = { exports: {} };
    const exports = module.exports;
${indented}
    return ${globalName};
  },
});
`

await writeFile(resolve(here, 'client.js'), wrapped, 'utf8')

if (!wrapped.includes('__ModuleLoader__')) throw new Error('output missing loader registration')
if (!wrapped.includes(`id: ${JSON.stringify(name)}`)) throw new Error('output missing module id')

console.log(`built ${name} -> client.js (${Buffer.byteLength(wrapped, 'utf8')} bytes)`)

const hostResult = await build({
  entryPoints: [resolve(here, 'host.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  legalComments: 'none',
  logLevel: 'warning',
  charset: 'utf8',
  // `SettingsForms.schema()` recognises the schema by identity: an inlined copy
  // would be a different class with the same shape, and the settings page would
  // never see this plugin's fields. It must come from the Host's own tree.
  external: HOST_EXTERNAL,
})

const hostBundle = hostResult.outputFiles?.[0]
if (!hostBundle) throw new Error('esbuild produced no host output')

const hostOut = `/**
 * ${name} — Host half.
 *
 * Generated by build.mjs from host.ts and src/*. Source of truth is the
 * TypeScript; do not edit this file by hand.
 */
${hostBundle.text}`

await writeFile(resolve(here, 'index.js'), hostOut, 'utf8')
console.log(`built ${name} -> index.js (${Buffer.byteLength(hostOut, 'utf8')} bytes)`)
